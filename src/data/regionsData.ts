export function getLocationCoordinates(
  region: string,
  district?: string,
  mfy?: string
): { lat: number; lng: number } {
  const baseDistrict = district ? DISTRICT_COORDINATES[district] : undefined;
  const baseRegion = REGION_COORDINATES[region] || { lat: 41.311081, lng: 69.240562 };
  const base = baseDistrict || baseRegion;

  if (!mfy || !district) {
    return base;
  }

  // Deterministic offset within the district for each MFY so the map pin moves to the mahalla area immediately
  const mfyList = getMfyListForDistrict(district);
  const idx = mfyList.indexOf(mfy);
  if (idx <= 0) {
    return base;
  }
  const angle = (idx * 137.5 * Math.PI) / 180;
  const radius = 0.004 + (idx % 4) * 0.0025;
  return {
    lat: Number((base.lat + Math.sin(angle) * radius).toFixed(6)),
    lng: Number((base.lng + Math.cos(angle) * radius).toFixed(6)),
  };
}
